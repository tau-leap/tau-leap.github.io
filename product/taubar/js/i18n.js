let currentLang = localStorage.getItem('taubar-lang') || (navigator.language.startsWith('ja') ? 'ja' : 'en');

export function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('taubar-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (STRINGS[lang]?.[key]) el.textContent = STRINGS[lang][key];
  });
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.textContent = lang === 'ja' ? 'JA' : 'EN';
    toggle.setAttribute('aria-label', STRINGS[lang]['a11y.language']);
  }
}

export function getLang() {
  return currentLang;
}

export function translate(key, lang = currentLang) {
  return STRINGS[lang]?.[key] || key;
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
  document.getElementById('langToggle')?.addEventListener('click', () => {
    applyLanguage(currentLang === 'en' ? 'ja' : 'en');
  });
});
